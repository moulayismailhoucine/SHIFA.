RTL_LANGS = {"ar"}


def translator(text: str, lang: str = "en") -> str:
    """Translate *text* into *lang*. Falls back to English."""
    if lang == "en" or not text:
        return text
    entry = TRANSLATIONS.get(text)
    if not entry:
        return text
    return entry.get(lang, text)


def get_lang(request: Request) -> str:
    """Resolve language from query param > cookie > accept-language header > default 'en'."""
    # 1. Query param
    q = request.query_params.get("lang")
    if q in ("en", "fr", "ar"):
        return q
    # 2. Cookie
    cookie = request.cookies.get("lang")
    if cookie in ("en", "fr", "ar"):
        return cookie
    # 3. Accept-Language header
    accept = request.headers.get("accept-language", "")
    for part in accept.replace(";", ",").split(","):
        part = part.strip().split("-")[0].lower()
        if part in ("en", "fr", "ar"):
            return part
    return "en"


def is_rtl(lang: str) -> bool:
    return lang in RTL_LANGS
